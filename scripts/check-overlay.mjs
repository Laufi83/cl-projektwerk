import { chromium } from "@playwright/test";
const out = process.argv[2];
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.addInitScript(() => localStorage.setItem("consent:v1", JSON.stringify({ necessary: true, stats: false, media: false, at: "x" })));
await page.goto("http://localhost:3100/", { waitUntil: "networkidle", timeout: 120000 });
await page.waitForFunction(() => window.__lenis, null, { timeout: 60000 });
await page.evaluate(() => window.__lenis.scrollTo(document.querySelector(".spiral-stage"), { immediate: true, force: true }));
await page.waitForTimeout(14000);
await page.getByRole("button", { name: "Öffnen", exact: true }).click();
await page.waitForTimeout(350);
await page.screenshot({ path: `${out}/o-flight.png`, timeout: 90000 });
await page.waitForTimeout(5000);
console.log("URL after open:", page.url());
await page.screenshot({ path: `${out}/o-open.png`, timeout: 90000 });
const dlg = page.locator("dialog.design-overlay");
await dlg.evaluate((d) => d.scrollTo(0, 1400));
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/o-open-scrolled.png`, timeout: 90000 });
await page.keyboard.press("Escape");
await page.waitForTimeout(3000);
console.log("URL after ESC:", page.url(), "dialog open:", await dlg.evaluate((d) => d.open));
await page.screenshot({ path: `${out}/o-closed.png`, timeout: 90000 });
await browser.close();
